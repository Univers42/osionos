/* genq.mjs — builds the literal-valued query files for the AI-P0b spike.
 *
 *   node genq.mjs
 *
 * Writes, next to this file:
 *   queries.sql  500 hybrid queries, all values inlined (so the planner can prune partitions)
 *   recall.sql   100 of those queries: index top-20 vs exact top-20 (recall@20)
 *   explain.sql  EXPLAIN (ANALYZE, BUFFERS) for a small / median / largest accessible workload
 *
 * Every literal is recomputed from gen.mjs's deterministic model, so the queries
 * are reproducible without the data load. No npm deps.
 */
import { writeFileSync, readFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { dirname, join } from 'node:path';
import {
	N_WORKSPACES, N_PAGES, CHUNKS_PER_PAGE, SEED,
	buildMembership, userWorkspaces, workspaceId, pageWorkspace,
	chunkWords, queryVectorNear, vecLiteral, rng,
} from './gen.mjs';

const HERE = dirname(fileURLToPath(import.meta.url));
const N_QUERIES = 500;
const RECALL_EVERY = 5; // queries 1,6,11,... -> 100 of them
const EF_SEARCH = 100;
const QUERY_SIGMA = 0.2;

// ---------------------------------------------------------------------------
// Model rebuild (identical to what gen.mjs used to print COPY rows).
// ---------------------------------------------------------------------------
const wsMembers = buildMembership();
const byUser = userWorkspaces(wsMembers);

const pageWs = new Int32Array(N_PAGES);
const pagesByWs = Array.from({ length: N_WORKSPACES }, () => []);
for (let p = 0; p < N_PAGES; p++) {
	const w = pageWorkspace(p);
	pageWs[p] = w;
	pagesByWs[w].push(p);
}

function userOfWorkspace(w, draw) {
	const list = wsMembers[w];
	return list[Math.floor(draw() * list.length)];
}

/** Deterministic query definition for index q (1-based). */
function buildQuery(q) {
	const r = rng('query', q);
	// Uniform over workspaces so small and large workspaces both show up.
	let w = -1;
	for (let attempt = 0; attempt < 64; attempt++) {
		const cand = Math.floor(r() * N_WORKSPACES);
		if (pagesByWs[cand].length > 0) {
			w = cand;
			break;
		}
	}
	if (w < 0) w = pageWs[0];
	const user = userOfWorkspace(w, r);
	const wsIdx = byUser.get(user).slice().sort((a, b) => a - b);
	const pages = pagesByWs[w];
	const page = pages[Math.floor(r() * pages.length)];
	const chunk = page * CHUNKS_PER_PAGE + Math.floor(r() * CHUNKS_PER_PAGE);

	const words = chunkWords(chunk);
	const nWords = 2 + Math.floor(r() * 2); // 2..3
	const start = Math.floor(r() * words.length);
	const picked = [];
	for (const off of [0, 7, 13]) {
		if (picked.length >= nWords) break;
		const word = words[(start + off) % words.length];
		if (!picked.includes(word)) picked.push(word);
	}
	while (picked.length < nWords) picked.push(words[(start + picked.length) % words.length]);

	const vec = queryVectorNear(chunk, q, QUERY_SIGMA);
	return {
		q,
		user,
		wsIdx,
		wsIds: wsIdx.map(workspaceId),
		text: picked.join(' '),
		vec: vecLiteral(vec),
		accessChunks: wsIdx.reduce((n, i) => n + pagesByWs[i].length * CHUNKS_PER_PAGE, 0),
	};
}

const queries = Array.from({ length: N_QUERIES }, (_, i) => buildQuery(i + 1));

// ---------------------------------------------------------------------------
// SQL fragments
// ---------------------------------------------------------------------------
const wsList = (ids) => `ARRAY[${ids.map((x) => `'${x}'::uuid`).join(',')}]`;

function accessPredicate(user) {
	// Mirrors scripts/bridge-page-read.mjs canReadPageRowAsMember (l.66-68) ->
	// canReadPageRow (l.57-58) -> canReadAsNonMember (l.52-53) ->
	// isOwnerOrCollaborator (l.47-49) with pageVisibility null-as-private (l.27-29).
	return `(
       visibility = 'shared'
       OR visibility = 'public'
       OR owner_id = '${user}'::uuid
       OR '${user}'::uuid = ANY (collaborator_ids)
     )`;
}

function hybridQuery(q) {
	const ws = wsList(q.wsIds);
	const acc = accessPredicate(q.user);
	const vec = `'${q.vec}'::halfvec(384)`;
	return `-- q${String(q.q).padStart(3, '0')} user=${q.user} workspaces=${q.wsIds.length} accessible_chunks=${q.accessChunks} text="${q.text}"
WITH v AS (
  SELECT id, row_number() OVER (ORDER BY embedding <=> ${vec}) AS r
  FROM ai_chunks
  WHERE workspace_id = ANY (${ws}) AND ${acc}
  ORDER BY embedding <=> ${vec} LIMIT 50
),
l AS (
  SELECT id, row_number() OVER (ORDER BY ts_rank_cd(tsv, query) DESC) AS r
  FROM ai_chunks, websearch_to_tsquery('simple', '${q.text}') query
  WHERE workspace_id = ANY (${ws}) AND ${acc} AND tsv @@ query
  ORDER BY ts_rank_cd(tsv, query) DESC LIMIT 50
)
SELECT id, sum(1.0 / (60 + r)) AS score
FROM (SELECT * FROM v UNION ALL SELECT * FROM l) u
GROUP BY id ORDER BY score DESC LIMIT 20;`;
}

const HEADER = `-- AI-P0b hybrid retrieval queries. Generated by genq.mjs (seed ${SEED}), do not hand-edit.
--
-- Access rule mirrored from scripts/bridge-page-read.mjs:
--   canReadPageRowAsMember (l.66-68): workspace_id in memberWorkspaceIds && canReadPageRow
--   canReadPageRow (l.57-58): visibility === 'shared' || canReadAsNonMember
--   canReadAsNonMember (l.52-53): visibility === 'public' || isOwnerOrCollaborator
--   isOwnerOrCollaborator (l.47-49): owner_id == user || a collaborator .userId == user
--   pageVisibility (l.27-29): null/unknown visibility -> 'private'
-- All values are literals so Postgres can prune the hash partitions at plan time.
SET hnsw.ef_search = ${EF_SEARCH};
SET hnsw.iterative_scan = relaxed_order;
\\timing on
`;

writeFileSync(join(HERE, 'queries.sql'), `${HEADER}\n${queries.map(hybridQuery).join('\n\n')}\n`);

// ---------------------------------------------------------------------------
// recall.sql — index top-20 vs exact top-20 for every 5th query.
// ---------------------------------------------------------------------------
function recallLeg(q, exact) {
	const ws = wsList(q.wsIds);
	const acc = accessPredicate(q.user);
	const vec = `'${q.vec}'::halfvec(384)`;
	return `INSERT INTO ${exact ? 'exact_top' : 'approx_top'}
SELECT ${q.q}, array_agg(id) FROM (
  SELECT id FROM ai_chunks
  WHERE workspace_id = ANY (${ws}) AND ${acc}
  ORDER BY embedding <=> ${vec} LIMIT 20
) s;`;
}

const recallQueries = queries.filter((q) => q.q % RECALL_EVERY === 1);

const recallSql = `-- AI-P0b recall@20. Generated by genq.mjs.
-- "exact" = sequential scan + sort (index scans disabled); "approx" = HNSW index.
CREATE TEMP TABLE exact_top (t int, ids bigint[]);
CREATE TEMP TABLE approx_top (t int, ids bigint[]);

SET hnsw.ef_search = ${EF_SEARCH};
SET hnsw.iterative_scan = relaxed_order;

-- exact: force heap ordering (no index scan on the vector column)
SET enable_indexscan = off;
SET enable_bitmapscan = off;
${recallQueries.map((q) => recallLeg(q, true)).join('\n')}

-- approx: HNSW available again
SET enable_indexscan = on;
SET enable_bitmapscan = on;
${recallQueries.map((q) => recallLeg(q, false)).join('\n')}

SELECT count(*) AS queries,
       round(avg(inter) / 20.0, 4) AS recall_at_20,
       min(inter) AS min_inter, max(inter) AS max_inter
FROM (
  SELECT e.t,
         (SELECT count(*) FROM (SELECT unnest(e.ids) INTERSECT SELECT unnest(a.ids)) i) AS inter
  FROM exact_top e JOIN approx_top a USING (t)
) x;
`;
writeFileSync(join(HERE, 'recall.sql'), recallSql);

// ---------------------------------------------------------------------------
// explain.sql — small / median / largest accessible workload.
// ---------------------------------------------------------------------------
const ranked = queries.slice().sort((a, b) => a.accessChunks - b.accessChunks);
const picks = [
	['small', ranked[0]],
	['median', ranked[Math.floor(ranked.length / 2)]],
	['largest', ranked[ranked.length - 1]],
];
const explainSql = `-- AI-P0b EXPLAIN targets. Generated by genq.mjs.
SET hnsw.ef_search = ${EF_SEARCH};
SET hnsw.iterative_scan = relaxed_order;
${picks.map(([label, q]) => `
\\echo '### ${label} (q${q.q}, accessible_chunks=${q.accessChunks})'
EXPLAIN (ANALYZE, BUFFERS) ${hybridQuery(q).split('\n').slice(1).join('\n')}`).join('\n')}
`;
writeFileSync(join(HERE, 'explain.sql'), explainSql);

process.stderr.write(
	`genq: wrote queries.sql (${queries.length}), recall.sql (${recallQueries.length}), explain.sql\n` +
	`  picks: ${picks.map(([l, q]) => `${l}=q${q.q}(${q.accessChunks})`).join(' ')}\n`,
);

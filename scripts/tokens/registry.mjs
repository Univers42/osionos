// Writes src/shared/config/palettes.generated.ts: the palette list the picker
// shows, with the swatches taken from each palette's own generated colours so
// the card previews exactly what selecting it paints.

import { resolvedTokens } from "./aliases.mjs";
import { PALETTES } from "./palettes.mjs";

export const GENERATED_REGISTRY = "src/shared/config/palettes.generated.ts";

// The first swatch is the canvas the cards float on, not the page: a page is
// the card itself, so it would repeat the surface swatch.
const SWATCH_TOKENS = ["--osio-bg-canvas", "--osio-bg-surface", "--osio-accent", "--osio-update", "--osio-fg-default"];

const entry = (palette) => {
  const tokens = resolvedTokens(palette, palette.signatureMode);
  const swatches = SWATCH_TOKENS.map((name) => JSON.stringify(tokens[name])).join(", ");
  return [
    "  {",
    `    id: ${JSON.stringify(palette.id)},`,
    `    label: ${JSON.stringify(palette.label)},`,
    `    description: ${JSON.stringify(palette.description)},`,
    `    signatureMode: ${JSON.stringify(palette.signatureMode)},`,
    `    swatches: [${swatches}],`,
    "  },",
  ].join("\n");
};

/** The whole registry module, ending in a newline. */
export function renderRegistry() {
  return `/* GENERATED by scripts/build-tokens.mjs from the seeds in scripts/tokens/palettes.mjs.
   Do not edit: change the seeds, then run \`npm run tokens\`. The CSS for these ids
   is in src/app/styles/tokens.generated.css. */

import type { PaletteMeta } from "./theme";

export const GENERATED_PALETTES: readonly PaletteMeta[] = [
${PALETTES.map(entry).join("\n")}
];
`;
}

// Writes the generated colour stylesheet as text: one block of colours per
// mode, then the aliases once.
//
// The default palette is declared on :root and on every [data-theme] element,
// so a subtree that sets its own data-theme gets a complete palette. The
// aliases repeat on [data-theme] for the same reason: a var() is resolved on
// the element that declares it, so an alias declared only on :root would keep
// pointing at the page's colours inside a subtree in the other mode.

import { ALIASES } from "./aliases.mjs";
import { PALETTES } from "./palettes.mjs";
import { modeTokens } from "./ramps.mjs";

export const GENERATED_STYLESHEET = "src/app/styles/tokens.generated.css";

const HEADER = `/* GENERATED by scripts/build-tokens.mjs from the seeds in scripts/tokens/palettes.mjs.
   Do not edit: change the seeds, then run \`npm run tokens\`. */`;

const SELECTORS = { light: ':root,\n[data-theme="light"]', dark: '[data-theme="dark"]' };

const block = (selector, declarations) =>
  `${selector} {\n${declarations.map(([name, value]) => `  ${name}: ${value};`).join("\n")}\n}`;

/** The whole generated stylesheet, ending in a newline. */
export function renderStylesheet() {
  const [defaultPalette] = PALETTES;
  const modes = Object.entries(SELECTORS).map(([mode, selector]) =>
    block(selector, Object.entries(modeTokens(defaultPalette, mode))),
  );
  const aliases = block(
    ":root,\n[data-theme]",
    Object.entries(ALIASES).map(([name, target]) => [name, `var(${target})`]),
  );
  return `${[HEADER, ...modes, aliases].join("\n\n")}\n`;
}

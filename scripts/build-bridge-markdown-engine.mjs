// Builds scripts/bridge-markdown-engine.mjs, the bridge's copy of the editor's Markdown
// import (osionos#240, ruling M240-11/13). The bridge image has no build stage and copies
// only scripts/bridge-*.mjs, so the conversion ships as a committed esbuild bundle of
// src/entities/block/model/markdownImport.ts. Its header records the engine commit and a
// hash of every bundled source; tests/bridge/bridge-markdown-engine-drift.test.mjs fails
// when either no longer matches the tree.
//
//   node scripts/build-bridge-markdown-engine.mjs           write the bundle
//   node scripts/build-bridge-markdown-engine.mjs --check   exit 1 when it drifted
//
// The engine commit is read with git; where git cannot read the submodule (a worktree
// mounted into a container), pass it as MARKDOWN_ENGINE_COMMIT.

import { execFileSync } from 'node:child_process';
import { createHash } from 'node:crypto';
import { readFileSync, writeFileSync } from 'node:fs';
import { createRequire } from 'node:module';
import { fileURLToPath } from 'node:url';

export const ESBUILD_VERSION = '0.25.12';
export const BUNDLE_PATH = 'scripts/bridge-markdown-engine.mjs';
export const ENTRY_PATH = 'src/entities/block/model/markdownImport.ts';
export const ENGINE_PATH = 'packages/markdown-engine';
const ROOT = fileURLToPath(new URL('../', import.meta.url));
const HEADER_LINE = /^\/\/ (esbuild|engine-commit|source-sha256): (\S+)$/gm;

/** esbuild comes with vite (pinned in pnpm-lock.yaml); it is resolved through vite so no dependency is added. */
function loadEsbuild() {
	const requireFromVite = createRequire(createRequire(import.meta.url).resolve('vite/package.json'));
	const esbuild = requireFromVite('esbuild');
	if (esbuild.version !== ESBUILD_VERSION) {
		throw new Error(`esbuild ${esbuild.version} found; the bundle is pinned to ${ESBUILD_VERSION}.`);
	}
	return esbuild;
}

/** The submodule's checked-out commit, or MARKDOWN_ENGINE_COMMIT; null when neither is known. */
export function engineCommit(env = process.env) {
	if (env.MARKDOWN_ENGINE_COMMIT) return env.MARKDOWN_ENGINE_COMMIT;
	try {
		return execFileSync('git', ['-C', `${ROOT}${ENGINE_PATH}`, 'rev-parse', 'HEAD'], { encoding: 'utf8', stdio: ['ignore', 'pipe', 'ignore'] }).trim();
	} catch {
		return null;
	}
}

/** sha256 over every bundled source, by repo-relative path in code-unit order: the content the bundle was built from. */
function sourceHashOf(inputPaths) {
	const hash = createHash('sha256');
	for (const path of [...inputPaths].sort()) hash.update(`${path}\0`).update(readFileSync(`${ROOT}${path}`)).update('\0');
	return hash.digest('hex');
}

/** The header fields of a bundle text: { esbuild, 'engine-commit', 'source-sha256' }. */
export function readHeader(text) {
	return Object.fromEntries([...text.slice(0, 1024).matchAll(HEADER_LINE)].map((match) => [match[1], match[2]]));
}

/** Builds the bundle in memory: { text, inputs, sourceHash }. */
export async function buildBundle({ commit }) {
	if (!/^[0-9a-f]{40}$/.test(String(commit))) throw new Error('The engine commit is unknown: run where git can read the submodule, or set MARKDOWN_ENGINE_COMMIT.');
	const result = await loadEsbuild().build({
		absWorkingDir: ROOT,
		entryPoints: [ENTRY_PATH],
		tsconfig: 'tsconfig.json',
		bundle: true,
		format: 'esm',
		platform: 'node',
		target: 'node22',
		legalComments: 'eof',
		metafile: true,
		write: false,
		logLevel: 'silent',
	});
	const inputs = Object.keys(result.metafile.inputs);
	// The bridge image carries no node_modules: a bundled npm package would be a silent new dependency.
	const fromPackages = inputs.filter((path) => path.includes('node_modules/'));
	if (fromPackages.length > 0) throw new Error(`The bundle pulls npm packages: ${fromPackages.join(', ')}`);
	const sourceHash = sourceHashOf(inputs);
	const header = [
		`// GENERATED by scripts/build-bridge-markdown-engine.mjs from ${ENTRY_PATH}. Do not edit: rebuild.`,
		`// esbuild: ${ESBUILD_VERSION}`,
		`// engine-commit: ${commit}`,
		`// source-sha256: ${sourceHash}`,
		'',
	].join('\n');
	return { text: header + result.outputFiles[0].text, inputs, sourceHash };
}

async function main(argv) {
	const { text } = await buildBundle({ commit: engineCommit() });
	if (!argv.includes('--check')) {
		writeFileSync(`${ROOT}${BUNDLE_PATH}`, text);
		console.log(`wrote ${BUNDLE_PATH} (${Buffer.byteLength(text)} bytes)`);
		return 0;
	}
	const committed = readFileSync(`${ROOT}${BUNDLE_PATH}`, 'utf8');
	if (committed === text) return 0;
	console.error(`${BUNDLE_PATH} drifted from its sources: run node scripts/build-bridge-markdown-engine.mjs`);
	return 1;
}

if (process.argv[1] === fileURLToPath(import.meta.url)) process.exitCode = await main(process.argv.slice(2));

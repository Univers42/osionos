// Regenerates the icon-picker catalogs (run inside the playground container):
//   node scripts/gen-icon-catalogs.mjs [path/to/emoji-test.txt] [path/to/noto-api.json]
// Sources (fetched when no local paths are given):
//   https://unicode.org/Public/emoji/latest/emoji-test.txt   (full RGI emoji set)
//   https://googlefonts.github.io/noto-emoji-animation/data/api.json (animated set)
// Outputs (committed, lazy-loaded chunks — never edit by hand):
//   src/shared/ui/molecules/EmojiPicker/emojiCatalog.generated.ts
//   src/shared/ui/molecules/IconPicker/notoAnimated.generated.ts

import { readFileSync, writeFileSync } from "node:fs";

const EMOJI_TEST_URL = "https://unicode.org/Public/emoji/latest/emoji-test.txt";
const NOTO_API_URL = "https://googlefonts.github.io/noto-emoji-animation/data/api.json";
const TONE_LIGHT = 0x1f3fb;

async function loadSource(localPath, url) {
  if (localPath) return readFileSync(localPath, "utf8");
  const res = await fetch(url);
  if (!res.ok) throw new Error(`fetch ${url} → ${res.status}`);
  return res.text();
}

// Mirror of applyEmojiTone() in src/shared/lib/emoji/emojiTone.ts — keep in sync.
function composeTone(codePoints, tone) {
  const rest = codePoints.slice(1);
  if (rest[0] === 0xfe0f) rest.shift();
  return [codePoints[0], tone, ...rest];
}

function parseEmojiTest(text) {
  const fullyQualified = new Set();
  const entries = [];
  const groups = [];
  let group = "";
  for (const line of text.split("\n")) {
    const groupMatch = /^# group: (.+)$/.exec(line);
    if (groupMatch) {
      group = groupMatch[1].trim();
      if (group !== "Component" && !groups.includes(group)) groups.push(group);
      continue;
    }
    const m = /^([0-9A-F ]+?)\s*;\s*fully-qualified\s*#\s*\S+\s+E[\d.]+\s+(.+)$/.exec(line);
    if (!m || group === "Component") continue;
    const codePoints = m[1].trim().split(/\s+/).map((h) => parseInt(h, 16));
    fullyQualified.add(codePoints.join("-"));
    if (m[2].includes("skin tone")) continue; // tone variants compose at runtime
    entries.push({ codePoints, name: m[2].trim(), group: groups.indexOf(group) });
  }
  for (const e of entries)
    e.tone = fullyQualified.has(composeTone(e.codePoints, TONE_LIGHT).join("-")) ? 1 : 0;
  return { entries, groups, fullyQualified };
}

function buildNotoLines(apiJson, emojiEntries) {
  const nameByKey = new Map();
  for (const e of emojiEntries)
    nameByKey.set(
      e.codePoints.filter((c) => c !== 0xfe0f).map((c) => c.toString(16)).join("_"),
      e.name,
    );
  return JSON.parse(apiJson)
    .icons.map((icon) => {
      const key = icon.codepoint
        .split("_")
        .filter((h) => h !== "fe0f")
        .join("_");
      const tag = (icon.tags?.[0] ?? "").replaceAll(":", "").replaceAll("-", " ");
      return `${icon.codepoint}|${nameByKey.get(key) ?? tag ?? icon.codepoint}`;
    })
    .join("\n");
}

function fileHeader(basename, doc) {
  const pad = basename.padEnd(48);
  return `/* ************************************************************************** */
/*                                                                            */
/*                                                        :::      ::::::::   */
/*   ${pad} :+:      :+:    :+:   */
/*                                                    +:+ +:+         +:+     */
/*   By: dlesieur <dlesieur@student.42.fr>          +#+  +:+       +#+        */
/*                                                +#+#+#+#+#+   +#+           */
/*   Created: 2026/07/12 12:00:00 by dlesieur          #+#    #+#             */
/*   Updated: 2026/07/12 12:00:00 by dlesieur         ###   ########.fr       */
/*                                                                            */
/* ************************************************************************** */

/**
 * GENERATED by scripts/gen-icon-catalogs.mjs — do not edit by hand.
 * ${doc}
 */
`;
}

async function main() {
  const [emojiTestPath, notoPath] = process.argv.slice(2);
  const emojiTest = await loadSource(emojiTestPath, EMOJI_TEST_URL);
  const notoJson = await loadSource(notoPath, NOTO_API_URL);
  const { entries, groups } = parseEmojiTest(emojiTest);

  const emojiLines = entries
    .map((e) => `${String.fromCodePoint(...e.codePoints)}|${e.name}|${e.group}|${e.tone}`)
    .join("\n");
  writeFileSync(
    "src/shared/ui/molecules/EmojiPicker/emojiCatalog.generated.ts",
    `${fileHeader("emojiCatalog.generated.ts", `Full RGI emoji set (${entries.length} base emoji, Unicode ${/# Version: ([\d.]+)/.exec(emojiTest)?.[1] ?? "latest"}) from unicode.org emoji-test.txt,
 * CLDR palette order. One entry per line: glyph|name|groupIndex|toneCapable(0/1);
 * skin-tone variants are composed at runtime by applyEmojiTone(). Parsed by
 * emojiCatalog.ts — lazy-loaded so none of this lands in the warm chunk.`)}
export const EMOJI_CATALOG_GROUPS: readonly string[] = ${JSON.stringify(groups)};

export const EMOJI_CATALOG_DATA = \`${emojiLines}\`;
`,
  );

  const notoLines = buildNotoLines(notoJson, entries);
  writeFileSync(
    "src/shared/ui/molecules/IconPicker/notoAnimated.generated.ts",
    `${fileHeader("notoAnimated.generated.ts", `Google Noto animated-emoji index (${notoLines.split("\n").length} entries) from the
 * noto-emoji-animation project. One entry per line: codepoint|name, where codepoint
 * is the underscore-joined URL segment of the gstatic asset
 * (https://fonts.gstatic.com/s/e/notoemoji/latest/<codepoint>/512.webp). Parsed by
 * AnimatedTab.tsx — lazy-loaded so none of this lands in the warm chunk.`)}
export const NOTO_ANIMATED_BASE = "https://fonts.gstatic.com/s/e/notoemoji/latest";

export const NOTO_ANIMATED_DATA = \`${notoLines}\`;
`,
  );
  console.log(`emoji catalog: ${entries.length} entries, ${groups.length} groups`);
  console.log(`noto animated: ${notoLines.split("\n").length} entries`);
}

await main();
